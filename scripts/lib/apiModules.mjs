/**
 * The SPA's API client, read as text: `frontend/src/lib/api.js` and every
 * domain module under `frontend/src/lib/api/` (D527).
 *
 * WHY THE MODULES EXIST. On `main` from 2 August to 3 October 2026, `api.js`
 * changed in 113 of 624 commits, because every new client method landed in
 * that one file and unrelated features collided there. A new API domain now
 * goes in its own file, `lib/api/<domain>.js`. Existing methods stay where
 * they are: 147 tests and scripts read `api.js` by path.
 *
 * WHY THE INDEX IS GENERATED (#4105). Until #4105 each module was re-exported
 * by one hand-written line in a block inside `api.js`, so `api.js` was still
 * edited by every new domain. The block now lives in its own generated file,
 * `lib/apiModules.generated.js`, which `scripts/build-api-index.mjs` writes
 * from the folder listing; `api.js` re-exports it with one line that never
 * changes. It is generated rather than a Vite `import.meta.glob` because the
 * modules are re-exported BY NAME (`import { verdictApi } from '../lib/api'`),
 * and ES module named exports must be static: a glob returns an object, which
 * cannot be re-exported name by name. A plain file also runs unchanged under
 * the node tests, where `import.meta.glob` does not exist.
 *
 * WHAT THIS DECIDES.
 *   - `clientSources` — which files hold client calls: `api.js` and every
 *     `.js` directly under `lib/api/`. Anything that compares client calls with
 *     Worker routes reads all of them, so a call cannot hide from the drift
 *     check by living in a module.
 *   - `renderApiIndex` — the exact text of the generated index for a set of
 *     modules: one `export * from './api/<name>.js';` line each, alphabetical,
 *     between `// api-modules:begin` and `// api-modules:end`.
 *   - `reexportProblems` — whether the generated index names exactly the
 *     modules on disk, one well-formed line each, in alphabetical order, and
 *     is byte-for-byte what `renderApiIndex` writes. A module missing from it
 *     is code nobody can reach through `api`.
 *   - `apiJsProblems` — whether `api.js` re-exports the index with its one
 *     line, and holds no hand-written module line of its own.
 *   - `extractClientCalls`, `normalizePath`, `classifyCalls` — the
 *     (METHOD, path) of each `request()` call and whether the Worker's resolved
 *     route table answers it. Lifted out of `../check-api-drift.mjs` unchanged
 *     so they can be tested on a source that is not the real one.
 */
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import { resolve } from 'node:path';

export const API_FILE_REL = 'frontend/src/lib/api.js';
export const API_MODULES_DIR_REL = 'frontend/src/lib/api';
/** The generated re-export index (#4105), beside `api.js`. */
export const API_INDEX_REL = 'frontend/src/lib/apiModules.generated.js';
/** The one line `api.js` carries for the index. */
export const API_INDEX_LINE = "export * from './apiModules.generated.js';";

export const REEXPORT_BEGIN = '// api-modules:begin';
export const REEXPORT_END = '// api-modules:end';

/** The line the index carries for module `name` (the file `lib/api/<name>.js`). */
export const reexportLine = (name) => `export * from './api/${name}.js';`;

const MODULE_NAME = /^[a-z][A-Za-z0-9]*$/;
const REEXPORT_LINE = /^export \* from '\.\/api\/([^'/]+)\.js';$/;

export const API_INDEX_HEADER = [
  '// GENERATED by scripts/build-api-index.mjs from the files in lib/api/ (#4105).',
  '// Do not edit: add or remove a module file and run `node scripts/build-api-index.mjs`.',
  "// api.js re-exports this file with one line; scripts/check-api-drift.mjs fails",
  '// while it is not exactly what the script writes.',
];

/** The generated index's text for these lines (one per module, as written). */
export function renderIndexLines(lines) {
  return [...API_INDEX_HEADER, REEXPORT_BEGIN, ...lines, REEXPORT_END, ''].join('\n');
}

/** The generated index for these module names: alphabetical, one line each. */
export function renderApiIndex(moduleNames) {
  return renderIndexLines([...moduleNames].sort().map(reexportLine));
}

/** Module names (file stems) directly under `dir`, sorted. Missing dir → []. */
export function listModules(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith('.js'))
    .map((e) => e.name.slice(0, -3))
    .sort();
}

/** `[{ file, src }]` — `api.js` first, then each module, relative to `root`. */
export function clientSources(root) {
  const out = [{ file: API_FILE_REL, src: readFileSync(resolve(root, API_FILE_REL), 'utf8') }];
  for (const name of listModules(resolve(root, API_MODULES_DIR_REL))) {
    const file = `${API_MODULES_DIR_REL}/${name}.js`;
    out.push({ file, src: readFileSync(resolve(root, file), 'utf8') });
  }
  return out;
}

/** The generated index's source under `root`, or null when it is missing. */
export function readApiIndex(root) {
  const file = resolve(root, API_INDEX_REL);
  return existsSync(file) ? readFileSync(file, 'utf8') : null;
}

/**
 * Every way the generated index (`indexSrc`) disagrees with the modules on
 * disk. An empty array means it is exactly what `build-api-index` writes.
 */
export function reexportProblems(indexSrc, moduleNames) {
  if (indexSrc == null) {
    return [`${API_INDEX_REL} is missing — run: node scripts/build-api-index.mjs`];
  }
  const problems = [];
  const lines = indexSrc.split('\n');
  const begin = lines.findIndex((l) => l.trim() === REEXPORT_BEGIN);
  const end = lines.findIndex((l) => l.trim() === REEXPORT_END);
  if (begin < 0 || end < 0 || end < begin) {
    return [`the API index has no re-export block (\`${REEXPORT_BEGIN}\` … \`${REEXPORT_END}\`) — run: node scripts/build-api-index.mjs`];
  }
  if (lines.filter((l) => l.trim() === REEXPORT_BEGIN).length > 1
    || lines.filter((l) => l.trim() === REEXPORT_END).length > 1) {
    problems.push('the API index has more than one re-export block');
  }
  const listed = [];
  for (const raw of lines.slice(begin + 1, end)) {
    const line = raw.trim();
    if (!line || line.startsWith('//')) continue;
    const m = line.match(REEXPORT_LINE);
    if (!m) { problems.push(`malformed line in the re-export block: ${line}`); continue; }
    listed.push(m[1]);
  }
  const onDisk = new Set(moduleNames);
  const inBlock = new Set(listed);
  for (const name of moduleNames) {
    if (!MODULE_NAME.test(name)) problems.push(`module name is not camelCase: lib/api/${name}.js`);
    if (!inBlock.has(name)) problems.push(`lib/api/${name}.js is missing from the re-export block — run: node scripts/build-api-index.mjs (it writes: ${reexportLine(name)})`);
  }
  for (const name of listed) {
    if (!onDisk.has(name)) problems.push(`re-export block names lib/api/${name}.js, which does not exist — run: node scripts/build-api-index.mjs`);
  }
  if (inBlock.size !== listed.length) problems.push('re-export block lists a module twice');
  const sorted = [...listed].sort();
  if (listed.join('\n') !== sorted.join('\n')) problems.push('re-export block is not in alphabetical order');
  if (!problems.length && indexSrc !== renderApiIndex(moduleNames)) {
    problems.push(`${API_INDEX_REL} is not exactly what build-api-index writes (hand-edited?) — run: node scripts/build-api-index.mjs`);
  }
  return problems;
}

/**
 * Every way `api.js` fails to re-export the generated index: it must carry
 * `API_INDEX_LINE` exactly once and no module line of its own (a hand-written
 * `export * from './api/<name>.js'` is the pre-#4105 block coming back).
 */
export function apiJsProblems(apiSrc) {
  const problems = [];
  const lines = apiSrc.split('\n').map((l) => l.trim());
  const count = lines.filter((l) => l === API_INDEX_LINE).length;
  if (count === 0) problems.push(`api.js does not re-export the generated index — it must carry: ${API_INDEX_LINE}`);
  if (count > 1) problems.push('api.js re-exports the generated index more than once');
  for (const l of lines) {
    if (REEXPORT_LINE.test(l)) problems.push(`api.js re-exports a module by hand (${l}); the generated index does that — remove the line`);
  }
  if (lines.includes(REEXPORT_BEGIN) || lines.includes(REEXPORT_END)) {
    problems.push('api.js carries an `api-modules` block; the block lives in the generated index now');
  }
  return problems;
}

