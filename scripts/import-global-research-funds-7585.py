#!/usr/bin/env python3
"""D7585: reproduce the additive, primary-source worldwide manager migration.

Run without arguments to write the unmerged migration, or with --check to
verify it. This reads the committed evidence manifest only; it never scrapes a
directory, connects to D1, or changes existing fund records or source verdicts.
Per-record dates retain the day the evidence was checked, at or before the
compilation review date. Once applied, keep this snapshot immutable and use a
new migration for changes.
"""
import argparse
import json
import re
import unicodedata
from datetime import date
from pathlib import Path
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "attached_assets/research-global-funds-2026-11-19.json"
MIGRATION = ROOT / "cloudflare-worker/sql/migrations/202611190015_7585_research_global_funds.sql"
SOURCE_NAME = "Axal VC verified global fund managers (2026-11-19)"


def key(value):
    return re.sub(r"[^a-z0-9]", "", unicodedata.normalize("NFKD", value).encode("ascii", "ignore").decode().lower())


def quote(value):
    return "NULL" if value is None else "'" + str(value).replace("'", "''") + "'"


def url_host(value):
    parsed = urlsplit(value)
    if parsed.scheme != "https" or not parsed.hostname or parsed.username or parsed.password:
        raise ValueError(f"Expected an HTTPS source URL: {value}")
    return parsed.hostname.removeprefix("www.")


def checked_date(value, label):
    if not isinstance(value, str) or not re.fullmatch(r"[0-9]{4}-[0-9]{2}-[0-9]{2}", value):
        raise ValueError(f"Expected an ISO calendar date for {label}: {value}")
    return date.fromisoformat(value)


def validate(data):
    source = data["source"]
    if source["name"] != SOURCE_NAME:
        raise ValueError("D7585 requires its own compilation source; never reuse an earlier source review.")
    reviewed_on = checked_date(source["checked_on"], "source.checked_on")
    url_host(source["published_url"])
    seen_ids, seen_hosts, seen_aliases = set(), set(), set()
    for fund in data["funds"]:
        uid = fund["uid"]
        if not re.fullmatch(r"axal-[a-z0-9]+", uid) or len(uid) > 64 or uid in seen_ids:
            raise ValueError(f"Invalid or repeated manager UID: {uid}")
        seen_ids.add(uid)
        aliases, hosts = fund["aliases"], fund["hosts"]
        if not aliases or key(fund["name"]) not in aliases or any(not re.fullmatch(r"[a-z0-9]+", a) for a in aliases):
            raise ValueError(f"Invalid manager aliases: {uid}")
        if seen_aliases.intersection(aliases) or len(set(aliases)) != len(aliases):
            raise ValueError(f"Overlapping manager aliases: {uid}")
        seen_aliases.update(aliases)
        if url_host(fund["website"]) not in hosts or any(url_host("https://" + host) != host for host in hosts):
            raise ValueError(f"Invalid official hosts: {uid}")
        if seen_hosts.intersection(hosts) or len(set(hosts)) != len(hosts):
            raise ValueError(f"Shared manager host needs review: {uid}")
        seen_hosts.update(hosts)
        if checked_date(fund["checked_on"], f"{uid}.checked_on") > reviewed_on:
            raise ValueError(f"Evidence date is later than compilation review: {uid}")
        if not fund["notes"] or not fund["evidence_urls"]:
            raise ValueError(f"Missing dated evidence: {uid}")
        if fund["source_url"] not in fund["evidence_urls"]:
            raise ValueError(f"Primary row citation is missing from evidence URLs: {uid}")
        for url in [fund["source_url"], *fund["evidence_urls"]]:
            url_host(url)
        countries = fund["hq_countries"]
        if bool(fund["hq"]) != bool(countries) or any(not re.fullmatch(r"[A-Z]{2}", c) for c in countries):
            raise ValueError(f"HQ evidence/country mismatch: {uid}")
    if not seen_ids:
        raise ValueError("No verified managers")


def sql_name_key(column):
    # These candidates have ASCII manager names. Host/UID aliases also match
    # older spellings; never infer a relationship from a similar name.
    value = f"lower(coalesce({column}, ''))"
    for char in (" ", ".", ",", "-", "_", "'", "’", "&", "(", ")"):
        value = f"replace({value}, {quote(char)}, '')"
    for code in (9, 10, 13):
        value = f"replace({value}, char({code}), '')"
    return value


def render(data):
    validate(data)
    source = data["source"]
    parts = [
        "-- D7585 (#7585): independently verified worldwide fund-manager links.\n"
        "-- Generated by scripts/import-global-research-funds-7585.py from the dated\n"
        "-- evidence manifest. Manager records do not assert a specific vehicle,\n"
        "-- fundraise, ticket, size, vintage, investment mandate or LP commitment.\n"
        "-- Preserve all existing records, reports, saved references and verdicts;\n"
        "-- exclude served manager aliases/hosts and never revive a retired UID.\n",
        "INSERT OR IGNORE INTO research_fund_sources\n"
        "  (source_name,title,publisher,published_url,terms_status,terms_quote,evidence_url,evidence,\n"
        "   verdict,verdict_reason,reviewed_on,repo_copy,repo_copy_note)\nVALUES (" + ",".join(map(quote, [
            source["name"], "Axal VC worldwide fund-manager evidence, 19 November 2026", "Axal VC",
            source["published_url"], "not found", None, None,
            "Independent compilation of names, official links and supported headquarters countries. The committed manifest records the first-party evidence checked for every entry; no third-party directory or website prose is republished.",
            "cite only", "Citation-only factual metadata; no permission to republish manager website content is asserted.",
            source["checked_on"], "attached_assets/research-global-funds-2026-11-19.json",
            "D7585. Official manager links remain on each row; this shared citation opens the complete evidence manifest. Unknown vehicle facts remain NULL.",
        ])) + ");\n",
    ]
    for country in data["country_additions"]:
        parts.append("INSERT OR IGNORE INTO research_countries (code,name,region) VALUES (" + ",".join(quote(country[k]) for k in ("code", "name", "region")) + ");\n")
    if data["hq_overrides"]:
        values = ",\n  ".join("(" + quote(override["raw"]) + "," + quote(target) + ")" for override in data["hq_overrides"] for target in override["targets"])
        parts.append("-- Add a complete new mapping only when no manual mapping or unmapped pin exists.\n"
            "WITH requested(raw_value,target) AS (VALUES\n  " + values + "),\n"
            "missing(raw_value) AS MATERIALIZED (\n"
            "  SELECT DISTINCT r.raw_value FROM requested r\n"
            "  WHERE NOT EXISTS (SELECT 1 FROM research_taxonomy_overrides o\n"
            "    WHERE o.kind = 'fund_hq' AND o.raw_value = r.raw_value)\n"
            ")\nINSERT OR IGNORE INTO research_taxonomy_overrides (kind,raw_value,target,method,note)\n"
            "SELECT 'fund_hq',r.raw_value,r.target,'manual','D7585: verified HQ countries in the worldwide manager evidence manifest.'\n"
            "FROM requested r JOIN missing m ON m.raw_value = r.raw_value;\n")
    values = []
    for fund in sorted(data["funds"], key=lambda f: f["uid"]):
        row = [fund[k] for k in ("uid", "name", "website", "hq", "source_url", "checked_on")]
        row += [json.dumps(fund[k], separators=(",", ":")) for k in ("aliases", "hosts")]
        values.append("(" + ",".join(map(quote, row)) + ")")
    parts.append("WITH candidates(uid,name,website,hq,source_url,as_of,aliases,hosts) AS (VALUES\n  " + ",\n  ".join(values) + "),\n"
        "-- Match the API's served-source rule. Withheld legacy rows are never\n"
        "-- overwritten or relabelled; these new IDs have independent evidence.\n"
        "served_base AS (\n"
        "  SELECT d.uid,d.name,d.fund_number,lower(trim(coalesce(d.website,''))) AS web\n"
        "  FROM research_fund_directory d\n"
        "  WHERE NOT EXISTS (SELECT 1 FROM research_fund_sources s\n"
        "    WHERE s.source_name = d.source_name AND s.verdict = 'not allowed')\n"
        "),\n"
        "authorities AS (\n"
        "  SELECT uid,name,fund_number,CASE WHEN instr(web,'://') > 0\n"
        "    THEN substr(web,instr(web,'://')+3) ELSE web END AS authority FROM served_base\n"
        "),\n"
        "host_ports AS (\n"
        "  SELECT uid,name,fund_number,substr(authority,1,min(instr(authority||'/','/'),\n"
        "    instr(authority||'?','?'),instr(authority||'#','#'))-1) AS host_port FROM authorities\n"
        "),\n"
        "bare_hosts AS (\n"
        "  SELECT uid,name,fund_number,rtrim(substr(host_port,1,instr(host_port||':',':')-1),'.') AS host FROM host_ports\n"
        "),\n"
        "-- Normalize the historical identities once, not for every candidate alias.\n"
        "served AS MATERIALIZED (\n"
        "  SELECT lower(uid) AS uid," + sql_name_key("name") + " AS name_key,\n"
        "    " + sql_name_key("fund_number") + " AS fund_number_key,\n"
        "    CASE WHEN substr(host,1,4) = 'www.' THEN substr(host,5) ELSE host END AS host FROM bare_hosts\n"
        ")\n"
        "INSERT OR IGNORE INTO research_fund_directory\n"
        "  (uid,name,website,linkedin,hq,fund_number,fund_size_cents,fund_date,quarter,fund_year,\n"
        "   sector_focus,notable_lps,eif_flag,eifo_flag,source_name,source_url,as_of)\n"
        "SELECT c.uid,c.name,c.website,NULL,c.hq,NULL,NULL,NULL,NULL,NULL,NULL,NULL,0,0,\n"
        "  " + quote(source["name"]) + ",c.source_url,c.as_of\n"
        "FROM candidates c\n"
        "WHERE NOT EXISTS (SELECT 1 FROM research_fund_directory_uid_moves m WHERE m.old_uid = c.uid)\n"
        "AND NOT EXISTS (\n"
        "  SELECT 1 FROM served s WHERE s.uid = c.uid\n"
        "    OR EXISTS (SELECT 1 FROM json_each(c.aliases) a\n"
        "      WHERE s.name_key = a.value OR s.uid = a.value\n"
        "        -- Only remove an explicitly recorded vehicle number; do not guess\n"
        "        -- suffixes from manager names such as Norrsken22 or Z47.\n"
        "        OR (s.fund_number_key <> '' AND (\n"
        "          s.name_key IN (a.value||s.fund_number_key,a.value||'fund'||s.fund_number_key)\n"
        "          OR s.uid IN (a.value||s.fund_number_key,a.value||'fund'||s.fund_number_key)))\n"
        "        OR substr(s.uid,1,length(a.value)+1) = a.value||'-')\n"
        "    OR EXISTS (SELECT 1 FROM json_each(c.hosts) h WHERE s.host = h.value)\n"
        ");\n")
    return "\n".join(parts)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the committed SQL differs")
    args = parser.parse_args()
    data = json.loads(MANIFEST.read_text())
    sql = render(data)
    if args.check:
        if not MIGRATION.exists() or MIGRATION.read_text() != sql:
            raise SystemExit("Worldwide fund migration differs from its evidence manifest; regenerate before applying.")
    else:
        MIGRATION.write_text(sql)
    print(f"{len(data['funds'])} verified manager candidates; migration {'matches' if args.check else 'written'}.")


if __name__ == "__main__":
    main()
