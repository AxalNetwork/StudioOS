#!/usr/bin/env node
/**
 * D4225 (#4225): build `cloudflare-worker/src/services/agents/skillLibrary.generated.ts`
 * from the "From Axal" skill library, `cloudflare-worker/src/services/agents/skills/`:
 * every `<slug>.md` (the SKILL.md, #3951's format) and its `cases/<slug>.json`
 * (the golden case, #3953's shape).
 *
 * The Worker cannot read files at run time, and its only Text module rule is
 * the legal folder's, so the library is embedded as data in a generated
 * module the seed (`services/agents/skillLibrarySeed.ts`) imports. The files
 * stay the source; the module is never edited by hand.
 *
 *   node scripts/build-skill-library.mjs           write the module
 *   node scripts/build-skill-library.mjs --check   exit 1 when it is stale
 */
import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'cloudflare-worker/src/services/agents/skills');
const OUT = join(ROOT, 'cloudflare-worker/src/services/agents/skillLibrary.generated.ts');

/** The library as data: one entry per skill, slug order. */
export function libraryEntries(dir = DIR) {
  const files = readdirSync(dir).filter((f) => f.endsWith('.md') && f !== 'README.md').sort();
  return files.map((f) => {
    const slug = f.slice(0, -3);
    const casePath = join(dir, 'cases', `${slug}.json`);
    const kase = existsSync(casePath) ? JSON.parse(readFileSync(casePath, 'utf8')) : null;
    return { slug, skill_md: readFileSync(join(dir, f), 'utf8'), cases: kase ? [kase] : [] };
  });
}

export function render(entries = libraryEntries()) {
  return `/**
 * D4225 (#4225): the "From Axal" skill library as data, generated by
 * \`node scripts/build-skill-library.mjs\` from \`services/agents/skills/\` (each
 * SKILL.md and its golden case). Never edit by hand; the library test fails
 * while it is stale. The seed (\`skillLibrarySeed.ts\`) creates each skill as a
 * draft with its cases, for H2's review, evals and publish (D4160).
 */
export type LibraryCase = { skill: string; version: number; note?: string; input: { records: Record<string, unknown> }; expect: { output: string; must_include: string[]; must_say_not_recorded: string[]; must_not_include: string[]; [k: string]: unknown } };
export type LibraryEntry = { slug: string; skill_md: string; cases: LibraryCase[] };

export const SKILL_LIBRARY: readonly LibraryEntry[] = ${JSON.stringify(entries, null, 2)};
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const next = render();
  const now = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (process.argv.includes('--check')) {
    if (now !== next) {
      console.error('✖ skillLibrary.generated.ts is stale: run node scripts/build-skill-library.mjs');
      process.exit(1);
    }
    console.log(`✓ skill library: ${libraryEntries().length} skills, generated module current.`);
  } else if (now === next) {
    console.log('cloudflare-worker/src/services/agents/skillLibrary.generated.ts is already current.');
  } else {
    writeFileSync(OUT, next);
    console.log('wrote cloudflare-worker/src/services/agents/skillLibrary.generated.ts');
  }
}
