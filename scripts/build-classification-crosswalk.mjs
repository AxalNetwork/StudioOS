#!/usr/bin/env node
/** D7821 (#7821): deterministic UK SIC seed from the reviewed asset and imported SIC_SECTORS; never opens a database. */
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {SIC_SECTORS} from './import-companies-house.mjs';
import {COMPANY_SECTOR_RULES} from '../cloudflare-worker/src/services/researchTaxonomy.ts';
const root=new URL('../',import.meta.url);
const asset=new URL('attached_assets/research-classification-crosswalk-2026-11-20.json',root);
const output=new URL('cloudflare-worker/sql/migrations/202611200106_7821_research_classification_crosswalk_uk_sic.sql',root);
const quote=value=>"'"+String(value).replaceAll("'","''")+"'";
export function buildClassificationCrosswalk(reviewed){
 if(reviewed.scheme!=='UK SIC'||reviewed.scheme_version!=='2007'||!reviewed.reviewed_on||!reviewed.reviewer||!reviewed.reason)throw Error('Missing reviewed UK SIC metadata');
 const byCode=new Map(reviewed.activities.map(row=>[row.code,row]));
 if(byCode.size!==reviewed.activities.length||byCode.size!==Object.keys(SIC_SECTORS).length)throw Error('Reviewed activities must cover SIC_SECTORS exactly once');
 const lines=Object.entries(SIC_SECTORS).sort(([a],[b])=>a.localeCompare(b)).map(([code,label])=>{
  const activity=byCode.get(code),market=COMPANY_SECTOR_RULES[label];
  if(!activity||!market||!activity.industry_code||!activity.industry_title)throw Error('Missing reviewed activity or market for '+code);
  const values=[reviewed.scheme,reviewed.scheme_version,code,'exact',reviewed.normalized_scheme,reviewed.normalized_version,activity.industry_code,activity.industry_title,'mapped',market,reviewed.reason,reviewed.reviewed_on,reviewed.reviewer];
  return 'INSERT INTO research_classification_crosswalk(scheme,scheme_version,code,match_kind,normalized_scheme,normalized_version,industry_code,industry_title,state,market_slug,reason,reviewed_on,reviewer) VALUES('+values.map(quote).join(',')+');';
 });
 return '-- D7821: generated by scripts/build-classification-crosswalk.mjs; edit the reviewed asset, never this seed.\n-- Market targets reuse SIC_SECTORS → COMPANY_SECTOR_RULES without a copied label dictionary.\n'+lines.join('\n')+'\n';
}
if(import.meta.url===`file://${process.argv[1]}`){
 const sql=buildClassificationCrosswalk(JSON.parse(readFileSync(asset,'utf8')));
 if(process.argv.includes('--check')){if(readFileSync(output,'utf8')!==sql){process.stderr.write('Classification seed differs; regenerate it.\n');process.exitCode=1;}else process.stdout.write('Classification crosswalk seed is current.\n');}
 else{writeFileSync(output,sql);process.stdout.write('Wrote '+fileURLToPath(output)+'\n');}
}
