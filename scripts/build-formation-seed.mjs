#!/usr/bin/env node
/**
 * D6690 (#6690, plan key C2 of #6680) — the formation catalogue's version 1, "legacy parity",
 * generated from the code arrays, never typed by hand.
 *
 *   node scripts/build-formation-seed.mjs            write cloudflare-worker/sql/migrations/<stamp>_6690_formation_catalogue_seed_v1.sql
 *   node scripts/build-formation-seed.mjs --check    exit 1 when the file on disk is not what the arrays generate
 *
 * The arrays it reads (each exported from its module):
 *   routes/legal.ts                    JURISDICTIONS, JURISDICTION_TEMPLATES, COUNSEL_REQUIRED_TEMPLATES, HANDOFF_NEXT_STEPS
 *   services/incorporationQuote.ts     STATE_FILING_FEES
 *   services/incorporationCompany.ts   JURISDICTION_MAP
 *   routes/compliance.ts               STANDARD_EVENTS
 *   services/incorporationPacket.ts    JURISDICTION_CERT_TITLES
 *
 * What version 1 holds, form by form (the six ids are the form keys, `legacy_gate = '1'`):
 *   - the form: label, offer mode `orderable` (today's gate still decides, D586/D601), legal-form
 *     family, and the JURISDICTIONS entry's display fields in `legacy_display_json`;
 *   - its jurisdiction: ISO country and subdivision from JURISDICTION_MAP; no registry name (no array holds one);
 *   - facts, each `provisional` or `not_recorded`, never `recorded` (no source was read):
 *       certificate_title            the packet's certificate title
 *       compliance_event_<n>         one STANDARD_EVENTS entry, as JSON, in order
 *       registration_where_operates  not_recorded, for us_wy_ccorp and us_de_llc
 *   - one fee line, the state filing fee: amount null, its named source as a `formation_sources` row;
 *   - pack items: each template as a document (Axal), then each next step (the founder).
 *     `counsel_required` is today's (the Wyoming charter) on the US forms and 1 on every
 *     item of the three non-US forms.
 *
 * Pure apart from the CLI: `seedSql(arrays)` returns the file's text, so a test can generate it
 * again and compare. The output has no clock in it: the same arrays give the same bytes.
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { spawnSync } from 'node:child_process';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MIGRATIONS = join(ROOT, 'cloudflare-worker/sql/migrations');
export const SEED_SUFFIX = '_6690_formation_catalogue_seed_v1.sql';
/** The day version 1 is published. A constant, so the file never depends on when it was generated. */
export const PUBLISHED_AT = '2026-11-16T00:00:00Z';
/** `published_by` for a version no person published: the seed migration itself. */
export const SEED_PUBLISHER = 0;
export const NON_US_COUNSEL = Object.freeze(['uk_ltd', 'sg_pte', 'ee_oy']);
export const OPERATES_NOT_RECORDED = Object.freeze(['us_wy_ccorp', 'us_de_llc']);
const DISPLAY_LEFT_OUT = new Set(['id', 'label', 'templates']);

const q = (v) => (v == null ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const V = '(SELECT id FROM formation_catalogue_versions WHERE version = 1)';
const formId = (key) => `(SELECT id FROM formation_entity_forms WHERE version_id = ${V} AND form_key = ${q(key)})`;
const sourceId = (title, url) => `(SELECT id FROM formation_sources WHERE title = ${q(title)} AND url IS ${q(url)} ORDER BY id LIMIT 1)`;

/** `US-DE` → { country: 'US', subdivision: 'DE' }; `GB` → { country: 'GB', subdivision: null }. */
export function place(code) {
  const [country, subdivision = null] = String(code).split('-');
  return { country, subdivision };
}
/** The authority a fee is paid to: its source's name before the first comma. */
export const payeeOf = (source) => String(source).split(',')[0].trim();

export function seedSql(a) {
  const out = [];
  const add = (s) => out.push(s);
  add(`-- D6690 (#6690, plan key C2 of #6680) — the formation catalogue's version 1, "legacy parity".
-- GENERATED by scripts/build-formation-seed.mjs from the code arrays. Never edit this file: a merged
-- seed is never changed, and a correction is a new version (D6689). Every fact is provisional or
-- not recorded, and no fee line has an amount (no source has been read yet, D4357).
-- STANDS ALONE under the runner: no BEGIN/COMMIT.
`);
  add(`INSERT INTO formation_catalogue_versions (version, status, notes)
  SELECT 1, 'draft', ${q('Version 1, legacy parity (D6690): generated from the code arrays by scripts/build-formation-seed.mjs. Every fact is provisional or not recorded; no fee line has an amount.')}
  WHERE NOT EXISTS (SELECT 1 FROM formation_catalogue_versions WHERE version = 1);`);

  // Sources: the fee schedules the code names. Not versioned; one row per title and URL.
  const sources = new Map();
  for (const j of a.JURISDICTIONS) {
    const fee = a.STATE_FILING_FEES[j.id];
    if (fee) sources.set(`${fee.source}\u0000${fee.source_url}`, fee);
  }
  for (const fee of sources.values()) {
    add(`INSERT INTO formation_sources (kind, title, url, publisher)
  SELECT 'registry', ${q(fee.source)}, ${q(fee.source_url)}, ${q(payeeOf(fee.source))}
  WHERE NOT EXISTS (SELECT 1 FROM formation_sources WHERE title = ${q(fee.source)} AND url IS ${q(fee.source_url)});`);
  }

  // Jurisdictions, in the order the forms first name them.
  const places = new Map();
  for (const j of a.JURISDICTIONS) {
    const p = place(a.JURISDICTION_MAP[j.id].jurisdiction);
    places.set(`${p.country}-${p.subdivision ?? ''}`, p);
  }
  for (const p of places.values()) {
    add(`INSERT INTO formation_jurisdictions (version_id, country, subdivision, registry_name, vocabulary_json)
  VALUES (${V}, ${q(p.country)}, ${q(p.subdivision)}, NULL, '{}');`);
  }

  for (const j of a.JURISDICTIONS) {
    const p = place(a.JURISDICTION_MAP[j.id].jurisdiction);
    const display = Object.fromEntries(Object.entries(j).filter(([k]) => !DISPLAY_LEFT_OUT.has(k)));
    add(`INSERT INTO formation_entity_forms (version_id, jurisdiction_id, form_key, label, offer_mode, legal_form_family, legacy_gate, legacy_display_json, allow_axal_collection)
  VALUES (${V}, (SELECT id FROM formation_jurisdictions WHERE version_id = ${V} AND country = ${q(p.country)} AND COALESCE(subdivision, '') = ${q(p.subdivision ?? '')}),
    ${q(j.id)}, ${q(j.label)}, 'orderable', ${q(a.JURISDICTION_MAP[j.id].legal_form)}, '1', ${q(JSON.stringify(display))}, 0);`);

    const fact = (key, value, status) => add(`INSERT INTO formation_form_facts (version_id, form_id, fact_key, value, status, blocking)
  VALUES (${V}, ${formId(j.id)}, ${q(key)}, ${q(value)}, ${q(status)}, 0);`);
    if (a.JURISDICTION_CERT_TITLES[j.id]) fact('certificate_title', a.JURISDICTION_CERT_TITLES[j.id], 'provisional');
    (a.STANDARD_EVENTS[j.id] ?? []).forEach((e, i) => fact(`compliance_event_${i + 1}`, JSON.stringify(e), 'provisional'));
    if (OPERATES_NOT_RECORDED.includes(j.id)) fact('registration_where_operates', null, 'not_recorded');

    const fee = a.STATE_FILING_FEES[j.id];
    if (fee) {
      add(`INSERT INTO formation_fee_lines (version_id, form_id, line_key, label, payee, collected_by, currency, amount_cents, timing, source_id, checked_on)
  VALUES (${V}, ${formId(j.id)}, 'state_filing_fee', 'State filing fee', ${q(payeeOf(fee.source))}, 'payee', ${q(String(fee.currency).toUpperCase())},
    ${q(fee.amount_cents)}, 'at_formation', ${sourceId(fee.source, fee.source_url)}, ${q(fee.checked_on)});`);
    }

    const counsel = (key) => (NON_US_COUNSEL.includes(j.id) || a.COUNSEL_REQUIRED_TEMPLATES.has(key) ? 1 : 0);
    j.templates.forEach((key, i) => add(`INSERT INTO formation_pack_items (version_id, form_id, item_key, phase, kind, acting_party, title, template_key, counsel_required, position)
  VALUES (${V}, ${formId(j.id)}, ${q(key)}, 'before_filing', 'document', 'axal', ${q(a.JURISDICTION_TEMPLATES[key].title)}, ${q(key)}, ${counsel(key)}, ${i});`));
    (a.HANDOFF_NEXT_STEPS[j.id] ?? []).forEach((step, i) => add(`INSERT INTO formation_pack_items (version_id, form_id, item_key, phase, kind, acting_party, title, template_key, counsel_required, position)
  VALUES (${V}, ${formId(j.id)}, ${q(`next_step_${i + 1}`)}, 'after_filing', 'step', 'founder', ${q(step)}, NULL, ${NON_US_COUNSEL.includes(j.id) ? 1 : 0}, ${100 + i});`));
  }

  // Publish last: the rows above can only be written while version 1 is a draft.
  add(`UPDATE formation_catalogue_versions SET status = 'published', published_by = ${SEED_PUBLISHER}, published_at = ${q(PUBLISHED_AT)}
  WHERE version = 1 AND status = 'draft';`);
  add(`UPDATE formation_catalogue_versions SET is_current = 1
  WHERE version = 1 AND status = 'published' AND NOT EXISTS (SELECT 1 FROM formation_catalogue_versions WHERE is_current = 1);`);
  return `${out.join('\n')}\n`;
}

/** The seed file already on disk, if any: its name keeps the minute it was first written. */
export function seedFile(dir = MIGRATIONS) {
  const name = readdirSync(dir).find((n) => n.endsWith(SEED_SUFFIX));
  return name ? join(dir, name) : null;
}

/** The arrays, read from the Worker modules (TypeScript: this runs under the test loader). */
export async function readArrays() {
  const src = (p) => pathToFileURL(join(ROOT, 'cloudflare-worker/src', p)).href;
  const legal = await import(src('routes/legal.ts'));
  const quote = await import(src('services/incorporationQuote.ts'));
  const company = await import(src('services/incorporationCompany.ts'));
  const compliance = await import(src('routes/compliance.ts'));
  const packet = await import(src('services/incorporationPacket.ts'));
  return {
    JURISDICTIONS: legal.JURISDICTIONS, JURISDICTION_TEMPLATES: legal.JURISDICTION_TEMPLATES,
    COUNSEL_REQUIRED_TEMPLATES: legal.COUNSEL_REQUIRED_TEMPLATES, HANDOFF_NEXT_STEPS: legal.HANDOFF_NEXT_STEPS,
    STATE_FILING_FEES: quote.STATE_FILING_FEES, JURISDICTION_MAP: company.JURISDICTION_MAP,
    STANDARD_EVENTS: compliance.STANDARD_EVENTS, JURISDICTION_CERT_TITLES: packet.JURISDICTION_CERT_TITLES,
  };
}

async function main() {
  const check = process.argv.includes('--check');
  const text = seedSql(await readArrays());
  const existing = seedFile();
  if (check) {
    if (!existing) { console.error('✗ build-formation-seed: no seed file; run node scripts/build-formation-seed.mjs'); process.exit(1); }
    if (readFileSync(existing, 'utf8') !== text) { console.error(`✗ build-formation-seed: ${existing} is not what the arrays generate`); process.exit(1); }
    console.log('✓ build-formation-seed: the seed file is what the arrays generate.');
    return;
  }
  const stamp = new Date().toISOString().replace(/[-:T]/g, '').slice(0, 12);
  const path = existing ?? join(MIGRATIONS, `${stamp}${SEED_SUFFIX}`);
  writeFileSync(path, text);
  console.log(`wrote ${path}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  if (!process.env.FORMATION_SEED_LOADED) {
    // The arrays are TypeScript modules: run again under the Worker tests' loader.
    const loader = join(ROOT, 'cloudflare-worker/test/_ts-loader.mjs');
    const r = spawnSync(process.execPath, ['--experimental-strip-types', '--no-warnings', '--import', pathToFileURL(loader).href, fileURLToPath(import.meta.url), ...process.argv.slice(2)],
      { stdio: 'inherit', env: { ...process.env, FORMATION_SEED_LOADED: '1' }, cwd: ROOT });
    process.exit(r.status ?? 1);
  }
  await main();
}
if (!existsSync(MIGRATIONS)) throw new Error(`no migrations folder at ${MIGRATIONS}`);
