#!/usr/bin/env node
/**
 * #6312: the coordinator's GitHub side, for the `coordinator-audit` skill.
 *
 *   snapshot --out DIR                 every open issue and PR, plus main's sha and the time
 *   delta    --out DIR [--since ISO]   the open issues a weekly pass must re-read (delta.json);
 *                                      --since defaults to the newest audit note in the last 30 days
 *   plan     --in RESULT.json --out DIR  verified findings → plan.json, proposals → proposals.json (both carry the run id)
 *   apply    --dir DIR --run ID [--go] notes, labels and closes from plan.json
 *   file     --dir DIR --run ID [--go] new tasks from proposals.json, then one list per parent
 *
 * Without `--go`, apply and file only print what they would do. Every write
 * carries the run's marker (`lib/coordinator.mjs`), and each issue is re-read
 * just before it is changed: if it moved since the snapshot it is skipped and
 * listed in `stale-<run>.json` for the next triage. Never merges, approves, or
 * touches code. GitHub access is curl with GH_TOKEN or GITHUB_TOKEN when set,
 * so it also works behind a proxy that injects credentials.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync, mkdirSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import {
  planLabels, describeLabelChange, slotPicker, slotLoad, proposalLabels, classifyProposal,
  marker, parseMarkers, alreadyDone, staleReasons, renderNote, planFromFindings, deltaSelect, RUN_ID,
} from './lib/coordinator.mjs';

const REPO = process.env.COORDINATOR_REPO || 'AxalNetwork/StudioOS';
const API = `https://api.github.com/repos/${REPO}`;
const FOOTER = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
const sleep = ms => new Promise(r => setTimeout(r, ms));

// The token goes in a private curl config file, never in argv, so a failed
// command line in an error message cannot carry it.
let authConfig = null;
function authArgs() {
  const token = process.env.GH_TOKEN || process.env.GITHUB_TOKEN;
  if (!token) return [];
  if (!authConfig) {
    const dir = mkdtempSync(join(tmpdir(), 'coord-'));
    authConfig = join(dir, 'auth.conf');
    writeFileSync(authConfig, `header = "Authorization: Bearer ${token.replace(/["\\\n]/g, '')}"\n`, { mode: 0o600 });
    process.on('exit', () => rmSync(dir, { recursive: true, force: true }));
  }
  return ['-K', authConfig];
}

export function gh(method, path, body) {
  const args = ['-sS', '-X', method, '-H', 'Accept: application/vnd.github+json', '-H', 'Content-Type: application/json',
    '-w', '\n%{http_code}', ...authArgs(), path.startsWith('https://api.github.com/') ? path : API + path];
  if (body !== undefined) args.push('--data-binary', '@-');
  let raw;
  try {
    raw = execFileSync('curl', args, { input: body === undefined ? undefined : JSON.stringify(body), encoding: 'utf8', maxBuffer: 1 << 28, stdio: ['pipe', 'pipe', 'pipe'] });
  } catch (e) { throw new Error(`${method} ${path}: curl failed (${String(e.stderr || '').trim().slice(0, 200)})`); }
  const cut = raw.lastIndexOf('\n');
  const status = Number(raw.slice(cut + 1));
  const text = raw.slice(0, cut);
  if (!(status >= 200 && status < 300)) { const e = new Error(`${method} ${path} → ${status}: ${text.slice(0, 200)}`); e.status = status; throw e; }
  try { return text.trim() ? JSON.parse(text) : null; } catch { throw new Error(`${method} ${path} → ${status}: not JSON`); }
}

function pages(path) {
  const all = [];
  for (let p = 1; p <= 100; p++) {
    const rows = gh('GET', `${path}${path.includes('?') ? '&' : '?'}per_page=100&page=${p}`);
    all.push(...rows);
    if (rows.length < 100) return all;
  }
  throw new Error('pagination cap reached');
}

const arg = (name, dflt) => { const i = process.argv.indexOf(`--${name}`); return i > 0 ? process.argv[i + 1] : dflt; };
const flag = name => process.argv.includes(`--${name}`);
const readJson = (p, d) => (existsSync(p) ? JSON.parse(readFileSync(p, 'utf8')) : d);
const writeJson = (p, v) => writeFileSync(p, JSON.stringify(v, null, 1));
const labelsOf = i => i.labels.map(l => (typeof l === 'string' ? l : l.name));
const slim = i => ({ number: i.number, title: i.title, state: i.state, state_reason: i.state_reason || null, body: i.body || '', labels: labelsOf(i), created_at: i.created_at, updated_at: i.updated_at });
const requireRun = (runId, recorded) => {
  if (!RUN_ID.test(String(runId || ''))) throw new Error('--run <id> is required: a letter or digit, then letters, digits, dot, dash or underscore');
  if (recorded && recorded !== runId) throw new Error(`--run ${runId} does not match the run ${recorded} this folder was planned for`);
};

function snapshot(out) {
  mkdirSync(out, { recursive: true });
  const at = new Date().toISOString();
  const all = pages('/issues?state=open');
  const issues = all.filter(i => !i.pull_request).map(slim);
  const prs = all.filter(i => i.pull_request).map(i => ({ number: i.number, title: i.title, body: i.body || '', labels: labelsOf(i), updated_at: i.updated_at }));
  const mainSha = gh('GET', '/commits/main').sha;
  writeJson(join(out, 'snapshot.json'), { at, mainSha, repo: REPO, issues, prs });
  console.log(`snapshot: ${issues.length} open issues, ${prs.length} open PRs, main ${mainSha.slice(0, 10)}, at ${at}`);
  return { at, mainSha, issues, prs };
}

function lastPass() {
  const from = new Date(Date.now() - 30 * 864e5).toISOString();
  let newest = null;
  for (const c of pages(`/issues/comments?since=${encodeURIComponent(from)}`)) {
    if (parseMarkers(c.body).some(m => m.kind === 'note') && (!newest || c.created_at > newest)) newest = c.created_at;
  }
  return newest;
}

function delta(out, since) {
  if (!since) { since = lastPass(); if (since) console.log(`--since defaults to the newest audit note: ${since}`); }
  if (!since || Number.isNaN(Date.parse(since))) throw new Error('no audit note in the last 30 days: pass --since <ISO time>, or run a full audit');
  const snap = snapshot(out);
  const lastNoteAt = {};
  for (const c of pages(`/issues/comments?since=${encodeURIComponent(since)}&sort=created&direction=asc`)) {
    if (!parseMarkers(c.body).some(m => m.kind === 'note')) continue;
    const n = Number(/\/issues\/(\d+)$/.exec(c.issue_url)?.[1]);
    if (n && (!lastNoteAt[n] || c.created_at > lastNoteAt[n])) lastNoteAt[n] = c.created_at;
  }
  const merged = pages(`/pulls?state=closed&sort=updated&direction=desc`).filter(p => p.merged_at && p.merged_at > since);
  const pick = deltaSelect({ issues: snap.issues, since, lastNoteAt, mergedPrBodies: merged.map(p => `${p.title}\n${p.body || ''}`) });
  const list = [...pick].map(([number, why]) => ({ number, why }));
  writeJson(join(out, 'delta.json'), { since, list });
  console.log(`delta since ${since}: ${list.length} of ${snap.issues.length} open issues to re-read (${merged.length} PRs merged since)`);
}

function plan(input, out) {
  const r = readJson(input);
  const result = r.result || r;
  const findings = (result.findings || []).filter(Boolean);
  const runId = result.runId;
  requireRun(runId);
  const steps = planFromFindings(findings);
  writeJson(join(out, 'plan.json'), { runId, steps });
  writeJson(join(out, 'proposals.json'), { runId, proposals: (result.proposals || []).filter(Boolean), unfiled: result.unfiled || [] });
  if ((result.privateNotes || []).length) {
    writeJson(join(out, 'private-notes.json'), result.privateNotes);
    console.log(`PRIVATE: ${result.privateNotes.length} security note(s) in private-notes.json. Send them to the owner privately; never post them on an issue.`);
  }
  const c = steps.reduce((a, s) => ({ notes: a.notes + !!s.note, labels: a.labels + !!s.labelChange, closes: a.closes + !!s.close }), { notes: 0, labels: 0, closes: 0 });
  console.log(`plan: ${steps.length} issues · ${c.notes} notes · ${c.labels} label changes · ${c.closes} closes · ${(result.proposals || []).length} proposals`);
}

async function apply(dir, runId, go) {
  const snap = readJson(join(dir, 'snapshot.json'));
  const { runId: planned, steps } = readJson(join(dir, 'plan.json'));
  requireRun(runId, planned);
  const bySnap = new Map(snap.issues.map(i => [i.number, i]));
  const ledgerPath = join(dir, `applied-${runId}.json`), stalePath = join(dir, `stale-${runId}.json`);
  const ledger = readJson(ledgerPath, {});
  const stale = {}; // only what THIS pass skipped; an earlier dry run's list never lingers
  const skip = (n, why) => { stale[n] = why; console.log(`#${n} skipped: ${why.join(', ')}`); };
  const date = snap.at.slice(0, 10);
  const recentMs = Date.now() - 3 * 864e5;
  for (const s of steps) {
    if (ledger[s.number] || (!s.note && !s.labelChange && !s.close)) continue;
    const base = bySnap.get(s.number);
    if (!base) { skip(s.number, ['not in the snapshot']); continue; }
    const live = slim(gh('GET', `/issues/${s.number}`));
    const fresh = pages(`/issues/${s.number}/comments?since=${encodeURIComponent(snap.at)}`).filter(c => c.created_at > snap.at);
    const noteDone = alreadyDone(fresh.map(c => c.body), runId, 'note');
    let why = staleReasons(base, live, fresh, runId);
    // An interrupted run of this plan posts its note BEFORE it closes, so a closed issue counts as ours only with our note on it and the close reason we planned.
    if (s.close && live.state === 'closed' && (!s.note || noteDone) && live.state_reason === s.close && why.every(w => w === 'closed since the snapshot' || w === 'labels changed')) {
      ledger[s.number] = 'closed by an earlier attempt of this run'; if (go) writeJson(ledgerPath, ledger); continue;
    }
    let lc = null, labelError = null;
    try { lc = s.labelChange ? planLabels(live.labels, s.labelChange, { kind: s.kind, activeClaim: live.labels.includes('state:in-progress') && Date.parse(live.updated_at) > recentMs }) : null; } catch (e) { labelError = e.message; }
    if (s.labelChange && why.includes('labels changed') && lc && !lc.changed) why = why.filter(w => w !== 'labels changed'); // already at the target
    if (why.length) { skip(s.number, why); continue; }
    if (labelError) console.log(`#${s.number}: label change refused (${labelError}); the note is posted without it`);
    const closeLabels = s.close ? live.labels.filter(l => !l.startsWith('state:') && l !== 'needs-decision' && l !== 'needs-design') : null;
    const body = s.note ? renderNote(s.note, { runId, mainSha: snap.mainSha, date, labelText: lc?.changed ? describeLabelChange(lc) : '', closing: s.close || false, footer: FOOTER }) : null;
    if (s.close && !body) { skip(s.number, ['a close needs its note']); continue; }
    console.log(`#${s.number}: ${body && !noteDone ? 'note' : ''}${lc?.changed ? ` labels(${describeLabelChange(lc)})` : ''}${s.close ? ` close(${s.close})` : ''}`);
    if (!go) continue;
    if (body && !noteDone) { gh('POST', `/issues/${s.number}/comments`, { body }); await sleep(1200); }
    if (lc?.changed || s.close) {
      gh('PATCH', `/issues/${s.number}`, s.close ? { labels: closeLabels, state: 'closed', state_reason: s.close } : { labels: lc.labels });
      await sleep(800);
    }
    ledger[s.number] = new Date().toISOString(); writeJson(ledgerPath, ledger);
  }
  if (go) writeJson(stalePath, stale);
  console.log(`${go ? 'applied' : 'dry run'}: ${Object.keys(ledger).length} done, ${Object.keys(stale).length} skipped${go ? ` (re-triage them: ${stalePath})` : ''}`);
}

async function file(dir, runId, go) {
  const { runId: planned, proposals, unfiled = [] } = readJson(join(dir, 'proposals.json'));
  requireRun(runId, planned);
  const ledgerPath = join(dir, `filed-${runId}.json`);
  const ledger = readJson(ledgerPath, {});
  const open = pages('/issues?state=open').filter(i => !i.pull_request);
  // Idempotency without the ledger: an issue this run already filed carries its key in a marker.
  for (const i of open) for (const m of parseMarkers(i.body)) if (m.run === runId && m.kind === 'file' && !ledger[m.key]) ledger[m.key] = { n: i.number, title: i.title, recovered: true };
  const pick = slotPicker(slotLoad(open));
  const openNumbers = new Set(open.map(i => i.number));
  const byParent = {};
  for (const p of proposals) {
    if (p.parent && !openNumbers.has(Number(p.parent))) { console.log(`parent #${p.parent} dropped for "${String(p.title).slice(0, 60)}": not an open issue`); p.parent = 0; }
    const key = String(p.key || '').replace(/[^\w:.-]/g, '-').slice(0, 128);
    if (!key) throw new Error(`proposal without a key: ${p.title}`);
    if (ledger[key]) { (byParent[p.parent] ||= []).push(ledger[key]); continue; }
    const kind = classifyProposal(p);
    const { labels, slot } = proposalLabels(p, kind === 'build' ? { slot: pick(), ready: !!p.ready_now } : {});
    let body = `S1: filed from the coordinator audit of ${new Date().toISOString().slice(0, 10)}${p.parent ? `, under #${p.parent}` : ''}. Size: ${p.size || 'M'}.\n\n${String(p.body).trim()}`;
    if (p.depends_on && !/## Dependencies/.test(body)) body += `\n\n## Dependencies\n${p.depends_on}`;
    if (kind === 'build' && !p.ready_now) body += '\n\n**State:** `state:blocked` until the dependencies above are met. Whoever closes the last one sets this to `state:ready`.';
    if (kind === 'brief') body += '\n\n**State:** a design brief. Session 1 turns it into a Claude Design canvas with the `design-brief` skill, for the owner to approve (AGENTS.md, Missing UI).';
    body += `\n\n${marker(runId, 'file', key)}${FOOTER}`;
    console.log(`file [${labels.join(' ')}]${p.parent ? ` under #${p.parent}` : ''} ${p.title.slice(0, 90)}`);
    if (!go) continue;
    const x = gh('POST', '/issues', { title: String(p.title).slice(0, 250), body, labels });
    ledger[key] = { n: x.number, title: p.title, kind, slot, ready: !!p.ready_now };
    writeJson(ledgerPath, ledger);
    (byParent[p.parent] ||= []).push(ledger[key]);
    await sleep(2500);
  }
  if (!go) return;
  for (const [parent, kids] of Object.entries(byParent)) {
    if (!Number(parent) || ledger[`parent:${parent}`]) continue;
    const prior = pages(`/issues/${parent}/comments`).map(c => c.body);
    if (alreadyDone(prior, runId, 'children', `p${parent}`)) { ledger[`parent:${parent}`] = true; continue; }
    const lines = kids.map(k => `- #${k.n} — ${k.title}${k.kind ? ` (${k.kind === 'build' ? `slot ${k.slot}, ${k.ready ? 'ready' : 'blocked on its dependencies'}` : k.kind === 'brief' ? 'design brief, S01' : 'owner decision, S01'})` : ''}`);
    gh('POST', `/issues/${parent}/comments`, { body: `S1: coordinator audit: tasks filed under this issue.\n\n${lines.join('\n')}\n\nThis issue stays open as their parent until they close.\n\n${marker(runId, 'children', `p${parent}`)}${FOOTER}` });
    ledger[`parent:${parent}`] = true; writeJson(ledgerPath, ledger);
    await sleep(2000);
  }
  // A proposal the dedupe check said belongs to an open issue is added there as a comment.
  for (const u of unfiled) {
    const c = u.check;
    if (!c || c.verdict !== 'add_as_comment_to_existing_issue' || !openNumbers.has(c.existing_issue)) continue;
    const key = `fold:${String(u.key).replace(/[^\w:.-]/g, '-')}`.slice(0, 128);
    if (ledger[key]) continue;
    if (alreadyDone(pages(`/issues/${c.existing_issue}/comments`).map(x => x.body), runId, 'fold', key)) { ledger[key] = true; continue; }
    gh('POST', `/issues/${c.existing_issue}/comments`, { body: `S1: coordinator audit: one more piece for this issue. It was proposed as a new task, and a check before filing found this issue already owns it.\n\n**${u.title}**\n\n${u.body || ''}\n\nWhy it belongs here: ${c.reason}\n\n${marker(runId, 'fold', key)}${FOOTER}` });
    ledger[key] = true; writeJson(ledgerPath, ledger); await sleep(2000);
  }
  console.log(`filed: ${Object.keys(ledger).filter(k => !k.startsWith('parent:') && !k.startsWith('fold:')).length} issues`);
}

async function main() {
  const cmd = process.argv[2];
  const dir = arg('dir', arg('out'));
  if (cmd !== 'plan' && !dir) throw new Error('--dir (or --out) is required');
  if (cmd === 'snapshot') snapshot(dir);
  else if (cmd === 'delta') delta(dir, arg('since'));
  else if (cmd === 'plan') { if (!dir || !arg('in')) throw new Error('plan needs --in and --out'); plan(arg('in'), dir); }
  else if (cmd === 'apply') await apply(dir, arg('run'), flag('go'));
  else if (cmd === 'file') await file(dir, arg('run'), flag('go'));
  else { console.error('usage: coordinator.mjs snapshot|delta|plan|apply|file (see the header)'); process.exit(2); }
}
if (import.meta.url === pathToFileURL(resolve(process.argv[1] || '')).href) {
  main().catch(e => { console.error(e.message); process.exit(1); });
}
