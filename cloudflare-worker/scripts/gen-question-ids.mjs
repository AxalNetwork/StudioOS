#!/usr/bin/env node
/**
 * Task #5 (CH) — Question ID type-gen.
 *
 * Walks the worker question banks and emits a TS string-literal union
 * + a JSON manifest at:
 *   - cloudflare-worker/src/services/advisor/questionIds.gen.ts
 *   - cloudflare-worker/src/services/advisor/banks.manifest.json
 *
 * The frontend `router.js::predictTarget` consumes the JSON manifest
 * for client-side optimistic page-target prediction (no monorepo
 * package needed — single source of truth lives in the worker).
 *
 * Re-run after editing any bank file. Wired into `npm run test:drift`
 * via `scripts/check-advisor-bank-drift.mjs` which calls --check first.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const WORKER_SRC = resolve(HERE, '../src/services/advisor');

// We avoid importing the TS sources (no compiler in CI ergonomics).
// Instead, we extract `id: '...'` literals from each bank file via a
// regex. Each ID line has the shape `id: 'ns.foo.bar'` and appears
// at most once per question literal. Robust against the SP/MA/ST/CV
// helper functions because the IDs are still string literals in source.
const BANK_FILES = {
  newFounderSpinout: 'banks/newFounderSpinout.ts',
  existingFounder:   'banks/existingFounder.ts',
  investor:          'banks/investor.ts',
  operatingPartner:  'banks/operatingPartner.ts',
  mentor:            'banks/mentor.ts',
};

const ID_REGEX = /\bid:\s*['"]([^'"]+)['"]/g;

function extractIds(filePath) {
  const src = readFileSync(filePath, 'utf8');
  const out = [];
  let m;
  while ((m = ID_REGEX.exec(src)) !== null) out.push(m[1]);
  return out;
}

// Extract page_target / doc_anchor for the manifest. We pair each id
// with the NEXT page_target/doc_anchor strings appearing in the same
// object literal — for most rows authored via helpers these come from
// the helper closure, so we fall back to per-bank defaults.
function buildManifest() {
  const manifest = {};
  for (const [bankName, rel] of Object.entries(BANK_FILES)) {
    const ids = extractIds(resolve(WORKER_SRC, rel));
    manifest[bankName] = ids.map((id) => ({ id }));
  }
  // Add the role detector ids hard-coded in questionBank.ts.
  const qbSrc = readFileSync(resolve(WORKER_SRC, 'questionBank.ts'), 'utf8');
  const detector = [];
  let m;
  const detectorRegex = /id:\s*['"](role_detect\.[a-z_]+)['"]/g;
  while ((m = detectorRegex.exec(qbSrc)) !== null) detector.push(m[1]);
  manifest.roleDetector = detector.map((id) => ({ id }));
  return manifest;
}

function emit(manifest) {
  const allIds = [];
  for (const rows of Object.values(manifest)) for (const r of rows) allIds.push(r.id);
  const unique = Array.from(new Set(allIds)).sort();

  const tsHeader = `// AUTO-GENERATED by cloudflare-worker/scripts/gen-question-ids.mjs.
// Do NOT edit by hand — re-run \`node cloudflare-worker/scripts/gen-question-ids.mjs\`
// (or \`npm run test:drift\`) after changing any bank file.
//
// Task #5 (CH) — string-literal union of every advisor question id
// across all persona banks + the role detector. Consumed by tools
// (Task #?) that need exhaustive switch coverage.
`;
  const tsBody = `export type AdvisorQuestionId =\n  | ${unique.map(id => `'${id}'`).join('\n  | ')};\n\nexport const ADVISOR_QUESTION_IDS: readonly AdvisorQuestionId[] = ${JSON.stringify(unique, null, 2)} as const;\n`;
  writeFileSync(resolve(WORKER_SRC, 'questionIds.gen.ts'), tsHeader + '\n' + tsBody);
  writeFileSync(resolve(WORKER_SRC, 'banks.manifest.json'),
    JSON.stringify({ generated_at: '__pinned__', banks: manifest }, null, 2) + '\n');
  return { unique, manifest };
}

function readEmittedIds() {
  try {
    const src = readFileSync(resolve(WORKER_SRC, 'questionIds.gen.ts'), 'utf8');
    const ids = [];
    const re = /'([^']+)'/g;
    let m;
    while ((m = re.exec(src)) !== null) ids.push(m[1]);
    return new Set(ids);
  } catch { return new Set(); }
}

const args = new Set(process.argv.slice(2));
const manifest = buildManifest();
const expected = new Set();
for (const rows of Object.values(manifest)) for (const r of rows) expected.add(r.id);

if (args.has('--check')) {
  const current = readEmittedIds();
  // current contains both the union literals AND the array literals,
  // so a true subset check vs expected is sufficient.
  const missing = [...expected].filter((id) => !current.has(id));
  const stale   = [...current].filter((id) => !expected.has(id));
  if (missing.length || stale.length) {
    console.error('[gen-question-ids] DRIFT: questionIds.gen.ts is out of date.');
    if (missing.length) console.error('  missing:', missing.slice(0, 20).join(', '), missing.length > 20 ? `(+${missing.length - 20} more)` : '');
    if (stale.length)   console.error('  stale:',   stale.slice(0, 20).join(', '),   stale.length   > 20 ? `(+${stale.length - 20} more)`   : '');
    console.error('  fix: `node cloudflare-worker/scripts/gen-question-ids.mjs`');
    process.exit(1);
  }
  console.log(`[gen-question-ids] OK — ${expected.size} ids in sync.`);
  process.exit(0);
}

const { unique } = emit(manifest);
console.log(`[gen-question-ids] wrote ${unique.length} ids → questionIds.gen.ts + banks.manifest.json`);
