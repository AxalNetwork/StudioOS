-- D5569 part 3: metadata-only reservation and audit for the disabled publisher broker.
CREATE TABLE IF NOT EXISTS agent_publish_requests (
  id INTEGER PRIMARY KEY,
  tenant_id INTEGER NOT NULL,
  company_id INTEGER NOT NULL REFERENCES company_profiles(id) ON DELETE CASCADE,
  project_id INTEGER NOT NULL REFERENCES projects(id) ON DELETE CASCADE,
  installation_uid TEXT NOT NULL REFERENCES venture_git_installations(uid),
  repository_full_name TEXT NOT NULL,
  target_ref TEXT NOT NULL,
  head_ref TEXT NOT NULL,
  task_id TEXT NOT NULL,
  agent_id TEXT NOT NULL,
  run_uuid TEXT NOT NULL,
  idempotency_key TEXT NOT NULL,
  intent_digest TEXT NOT NULL,
  patch_digest TEXT NOT NULL,
  candidate_sha TEXT NOT NULL,
  base_sha TEXT NOT NULL,
  work_intent_uid TEXT NOT NULL,
  approvals_json TEXT NOT NULL,
  state TEXT NOT NULL CHECK (state IN ('reserved', 'published', 'refused', 'unknown')),
  created_at_ms INTEGER NOT NULL,
  attempts INTEGER NOT NULL DEFAULT 1 CHECK (attempts BETWEEN 1 AND 5),
  retry_at_ms INTEGER,
  last_outcome_at_ms INTEGER,
  pr_number INTEGER,
  pr_url TEXT,
  deploy_sha TEXT,
  UNIQUE (tenant_id, company_id, project_id, installation_uid, task_id),
  UNIQUE (tenant_id, company_id, project_id, installation_uid, idempotency_key),
  CHECK ((state = 'published' AND pr_number > 0 AND pr_url IS NOT NULL) OR state <> 'published'),
  CHECK (length(candidate_sha) = 40 AND candidate_sha NOT GLOB '*[^0-9a-f]*')
);
CREATE INDEX IF NOT EXISTS idx_agent_publish_requests_pending ON agent_publish_requests (tenant_id, state);
