test('10. a D1 error, a slow read or a non-HTML shell passes through untouched', async () => {
  // Mutation checked: the deadline removed → the slow case hangs past it; the catch removed → a 500.
  const db = fixture();
  const broken = envFor(db);
  broken.env.DB = { prepare: () => { throw new Error('D1 down'); } };
  let r = await get(broken.env, '/events/demo-day');
  assert.equal(r.status, 200);
  assert.equal(r.text, SHELL);
  const slow = envFor(db);
  slow.env.DB = { prepare: () => ({ bind: () => ({ first: () => new Promise(() => {}) }) }) };
  const t0 = Date.now();
  r = await get(slow.env, '/events/demo-day');
  assert.equal(r.text, SHELL);
  assert.ok(Date.now() - t0 < CARD_DEADLINE_MS + 1000, 'the deadline holds');
  const json = envFor(db);
  json.env.ASSETS = { fetch: async () => new Response('{"a":1}', { status: 200, headers: { 'content-type': 'application/json' } }) };
  r = await get(json.env, '/events/demo-day');
  assert.equal(r.text, '{"a":1}');
  assert.equal(rewriteShell('<html><head></head></html>', sectionTags('event')), null, 'no managed block: nothing to replace');
});

test('11. headers are the shell\'s own, never the Worker CSP or no-referrer; HEAD answers with no body', async () => {
  // Mutation checked: the branch moved behind app.fetch → the nonce CSP and no-referrer appear.
  const { env } = envFor(fixture());
  const r = await get(env, '/events/demo-day');
  for (const [k, v] of Object.entries(SHELL_HEADERS)) assert.equal(r.headers.get(k), v, k);
  assert.equal(r.headers.get('content-security-policy'), null);
  assert.notEqual(r.headers.get('referrer-policy'), 'no-referrer');
  assert.equal(r.headers.get('cache-control'), 'public, max-age=0, must-revalidate', 'the shell\'s cache-control is kept');
  assert.equal(r.headers.get('etag'), null, 'the shell\'s etag no longer describes these bytes');
  const head = await get(env, '/events/demo-day', { method: 'HEAD' });
  assert.equal(head.status, 200);
  assert.equal(head.text, '');
  assert.match(head.headers.get('content-type')!, /text\/html/);
  // In fetch(): after the /assets/* block, before the first app.fetch a page load reaches.
  const index = readFileSync(resolve(ROOT, 'cloudflare-worker/src/index.ts'), 'utf8');
  const start = index.indexOf('export default {');
  const at = (needle: string) => index.indexOf(needle, start);
  assert.ok(at('serveSocialCard(request, env)') > at("pathname.startsWith('/assets/')"), 'after the /assets/* block');
  assert.ok(at('serveSocialCard(request, env)') < at("if (!pathname.startsWith('/api/'))"), 'before Hono answers a page load');
  // The _headers file and the constant agree.
  const file = readFileSync(resolve(ROOT, 'frontend/public/_headers'), 'utf8');
  for (const [k, v] of Object.entries(SHELL_HEADERS)) assert.ok(file.toLowerCase().includes(`${k}: ${v}`.toLowerCase()), `${k} matches _headers`);
});

