/** The env the Worker sees, with D1 calls counted. */
function envFor(db: any, over: Record<string, unknown> = {}) {
  const calls: string[] = [];
  const base = d1Over(db);
  const DB = new Proxy(base, { get: (t: any, k) => (k === 'prepare' ? (sql: string) => { calls.push(sql); return t.prepare(sql); } : t[k]) });
  const assets: { requests: Request[] } = { requests: [] };
  const ASSETS = {
    fetch: async (req: Request) => {
      assets.requests.push(req);
      return new Response(req.method === 'HEAD' ? null : SHELL, {
        status: 200, headers: { 'content-type': 'text/html; charset=utf-8', 'cache-control': 'public, max-age=0, must-revalidate', etag: '"shell"' },
      });
    },
  };
  return { env: { DB, ASSETS, ENVIRONMENT: 'development', JWT_SECRET: 'x'.repeat(48), ...over } as any, calls, assets };
}

async function get(env: any, path: string, init: RequestInit = {}) {
  const saved = console.warn; console.warn = () => {};
  try {
    const res = (await serveSocialCard(new Request(`https://axal.vc${path}`, init), env))!;
    return { status: res.status, headers: res.headers, text: await res.text() };
  } finally { console.warn = saved; }
}
const meta = (html: string, prop: string) => new RegExp(`<meta (?:property|name)="${prop.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}" content="([^"]*)"`).exec(html)?.[1] ?? null;
const titleOf = (html: string) => /<title>([^<]*)<\/title>/.exec(html)?.[1] ?? null;

