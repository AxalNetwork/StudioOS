/** Every `application/ld+json` block in a page, parsed. Index scanning, not a regex over the body. */
function ldBlocks(html: string): any[] {
  const out: any[] = [];
  const open = '<script type="application/ld+json">';
  for (let at = html.indexOf(open); at !== -1; at = html.indexOf(open, at + 1)) {
    const start = at + open.length;
    out.push(JSON.parse(html.slice(start, html.toLowerCase().indexOf('</script', start))));
  }
  return out;
}

function keysOf(v: any, into: string[] = []): string[] {
  if (Array.isArray(v)) v.forEach((x) => keysOf(x, into));
  else if (v && typeof v === 'object') for (const [k, x] of Object.entries(v)) { into.push(k); keysOf(x, into); }
  return into;
}

async function page(path: string) {
  const res = (await serveSocialCard(new Request(`https://axal.vc${path}`), envFor()))!;
  return res.text();
}

test('an article carries its own Article from the record, and not the home Organization', async () => {
  // Mutation checked: `withStructuredData` dropped from rewriteShell → the home Organization stays and no Article is written.
  const html = await page('/articles/ledgers');
  const blocks = ldBlocks(html);
  assert.deepEqual(blocks.map((b) => b['@type']), ['Article']);
  const [a] = blocks;
  assert.equal(a.headline, 'Why ledgers drift </script><script>alert(1)</script>', 'the title survives as data');
  assert.deepEqual(a.author, { '@type': 'Person', name: 'Ada Quill' });
  assert.equal(a.datePublished, '2026-10-01T09:00:00Z');
  assert.equal(a.dateModified, '2026-10-03T12:30:00Z');
  assert.equal(a.url, 'https://axal.vc/articles/ledgers');
  assert.equal(a.image, 'https://axal.vc/api/articles/cover/5');
  // Mutation checked: `jsonLdScript` without the `<` escape → the title closes the element and this count is 3.
  assert.equal(html.toLowerCase().split('</script').length - 1, 2, 'only the JSON-LD block and the module script close');
});

test('an article with no author name and no later edit leaves both out', async () => {
  // Mutation checked: dateModified written unconditionally → it appears here, a day before publication.
  const [a] = ldBlocks(await page('/articles/unedited'));
  assert.equal(a['@type'], 'Article');
  assert.equal('author' in a, false);
  assert.equal('dateModified' in a, false);
  assert.equal('description' in a, false);
  assert.equal('image' in a, false);
});

test('an event carries Event only with a start date and a place or an online format', async () => {
  // Mutation checked: the place-or-online gate removed → `nowhere` gets an Event with no location.
  const online = ldBlocks(await page('/events/online-day'));
  assert.deepEqual(online.map((b) => b['@type']), ['Event']);
  assert.equal(online[0].startDate, '2026-12-01T17:00:00Z');
  assert.equal(online[0].endDate, '2026-12-01T19:00:00Z');
  assert.equal(online[0].eventAttendanceMode, 'https://schema.org/OnlineEventAttendanceMode');
  assert.deepEqual(online[0].location, { '@type': 'VirtualLocation' });

  const geneva = ldBlocks(await page('/events/in-geneva'))[0];
  assert.equal(geneva.eventAttendanceMode, 'https://schema.org/OfflineEventAttendanceMode');
  assert.deepEqual(geneva.location, { '@type': 'Place', name: 'Rue Synthétique 1, Geneva', address: 'Rue Synthétique 1, Geneva' });
  assert.equal('endDate' in geneva, false);

  const hybrid = ldBlocks(await page('/events/hybrid'))[0];
  assert.equal(hybrid.eventAttendanceMode, 'https://schema.org/MixedEventAttendanceMode');
  assert.deepEqual(hybrid.location.map((l: any) => l['@type']), ['Place', 'VirtualLocation']);

  assert.deepEqual(ldBlocks(await page('/events/nowhere')), [], 'in person with no place recorded: no Event, and no Organization');
});

test('no record block carries a price, a join link, a rating or a review', async () => {
  // Mutation checked: `offers: { price: r.price_cents }` added to eventLd → the forbidden-key check fails.
  for (const path of ['/articles/ledgers', '/articles/unedited', '/events/online-day', '/events/in-geneva', '/events/hybrid']) {
    const html = await page(path);
    const blocks = ldBlocks(html);
    for (const k of keysOf(blocks)) assert.ok(!FORBIDDEN_LD_KEYS.includes(k), `${path} carries ${k}`);
    const json = JSON.stringify(blocks);
    assert.doesNotMatch(json, /join-secret|meet\.example|2500|"25(?:\.00)?"/, `${path} never carries the join link or price`);
  }
});
