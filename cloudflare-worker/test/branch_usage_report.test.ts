test('a branch reports every stream it cannot measure, with a reason for each', async () => {
  const { env } = branchEnv();
  const s = await branchRevenueSummary(env, '2026-Q3');

  assert.equal(s.branch, 'fr');
  assert.deepEqual(s.streams.map((x) => x.stream), ['subscriptions', 'licence_fees', 'token_margin']);
  for (const x of s.streams) {
    assert.equal(x.available, false, `${x.stream} claims to be measurable`);
    assert.equal(x.gross_cents, null, `${x.stream} reported a figure it says it cannot measure`);
    assert.ok(String(x.reason || '').length > 20, `${x.stream} is absent with no usable reason`);
  }
});

test('the token COST is carried as a basis, never as revenue', async () => {
  // The one measured number on a branch. Reporting it as `token_margin`'s
  // gross would let a statement sum a COST as revenue — so it rides in
  // `estimate_basis`, which nothing adds up.
  const { env, db } = branchEnv();
  const ins = db.prepare('INSERT INTO ai_usage_logs (est_cost_usd, created_at) VALUES (?,?)');
  ins.run(10.25, '2026-08-01T00:00:00Z');
  ins.run(2.5, '2026-09-30T23:59:59Z');
  ins.run(99, '2026-10-01T00:00:01Z');   // Q4 — must not be counted
  ins.run(99, '2026-06-30T23:59:59Z');   // Q2 — must not be counted

  const s = await branchRevenueSummary(env, '2026-Q3');
  const token = s.streams.find((x) => x.stream === 'token_margin')!;
  assert.equal(token.gross_cents, null);
  assert.equal(token.is_estimate, true);
  assert.match(String(token.estimate_basis), /USD 12\.75/, 'the quarter bounds let another quarter in');
  assert.match(String(token.estimate_basis), /2 calls/);
});

test('branchRevenueSummary refuses a period that is not a quarter, and refuses to run at HQ', async () => {
  const { env } = branchEnv();
  await assert.rejects(() => branchRevenueSummary(env, '2026-13'), /is not a period/);
  const atHq = { ...env, BRANCH_CODE: '' };
  await assert.rejects(() => branchRevenueSummary(atHq, '2026-Q3'), /only live on a branch/);
});

test('a pushed ceiling is stored as one dated copy and leaves the issued figure alone', async () => {
  const { env, db } = branchEnv();
  db.prepare(
    'INSERT INTO branch_promo_ceiling (id, period, ceiling_cents, currency, issued_cents) VALUES (1,?,?,?,?)',
  ).run('2026-Q3', 100_000, 'EUR', 40_000);

  await applyPromoCeiling(env, {
    period: '2026-Q3', ceiling_cents: 500_000, currency: 'eur', pushed_at: '2026-09-15T10:00:00Z',
  });

  const rows = db.prepare('SELECT * FROM branch_promo_ceiling').all() as any[];
  assert.equal(rows.length, 1, 'a second ceiling row appeared on the branch');
  assert.equal(rows[0].ceiling_cents, 500_000);
  assert.equal(rows[0].currency, 'EUR', 'the currency was stored as it arrived rather than normalised');
  assert.equal(rows[0].pushed_at, '2026-09-15T10:00:00Z');
  // THE BRANCH OWNS THIS ONE. A push that reset it would erase the branch's
  // own count every time HQ moved the ceiling.
  assert.equal(rows[0].issued_cents, 40_000, 'a ceiling push erased the branch\'s issued figure');
});

test('applyPromoCeiling refuses to run at HQ', async () => {
  const { env, db } = branchEnv();
  const atHq = { ...env, BRANCH_CODE: '' };
  await assert.rejects(() => applyPromoCeiling(atHq, {
    period: '2026-Q3', ceiling_cents: 1, currency: 'EUR', pushed_at: '2026-09-15T10:00:00Z',
  }), /only live on a branch/);
  assert.equal((db.prepare('SELECT COUNT(*) AS n FROM branch_promo_ceiling').get() as any).n, 0);
});
