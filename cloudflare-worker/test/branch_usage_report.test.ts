test('a report writes one row per stream, stamped by the branch', async () => {
  const { env, db } = await hqEnv();
  const r = await reportUsage(env, 'fr', SECRET, '2026-Q3', figures([
    { stream: 'token_margin', gross_cents: null, currency: 'USD', available: false, estimate_basis: 'cost was USD 12.00' },
  ]));
  assert.deepEqual(r, { ok: true, period: '2026-Q3', streams: 2 });

  const rows = db.prepare('SELECT * FROM subsidiary_usage_reports ORDER BY stream').all() as any[];
  assert.equal(rows.length, 2);
  assert.equal(rows[0].stream, 'other');
  assert.equal(rows[0].gross_cents, 400_000);
  assert.equal(rows[0].licence_uid, 'lic_fr', 'the report was filed against the wrong licence');
  assert.equal(rows[0].branch_code, 'fr');
  assert.ok(rows[0].reported_at, 'a report arrived with no stamp');
});

test('a figure the branch could not measure is stored NULL, never 0', async () => {
  const { env, db } = await hqEnv();
  await reportUsage(env, 'fr', SECRET, '2026-Q3', [
    { stream: 'subscriptions', gross_cents: null, currency: 'EUR', available: false },
    // available:false WITH a number — the branch sent a figure it does not
    // stand behind, and the flag is what decides, not the presence of a value.
    { stream: 'licence_fees', gross_cents: 999, currency: 'EUR', available: false },
  ] as any);

  const rows = db.prepare('SELECT stream, gross_cents FROM subsidiary_usage_reports ORDER BY stream').all() as any[];
  assert.equal(rows.find((x) => x.stream === 'subscriptions').gross_cents, null);
  assert.equal(rows.find((x) => x.stream === 'licence_fees').gross_cents, null,
    'an unavailable stream kept a number the branch disclaimed');
});

test('a figure that is not a finite number is stored NULL, never coerced to 0 (D266)', async () => {
  // THE ONE READING THIS FUNCTION EXISTS TO REFUSE. `Number(x) || 0` turned a
  // figure that did not parse into a zero, which a statement then sums as a
  // measured quarter that earned nothing. Not parsing is not measuring.
  const { env, db } = await hqEnv();
  await reportUsage(env, 'fr', SECRET, '2026-Q3', [
    { stream: 'a', gross_cents: 'not a number' },
    { stream: 'b', gross_cents: Number.NaN },
    { stream: 'c', gross_cents: Number.POSITIVE_INFINITY },
    { stream: 'd', gross_cents: '1234.9' },
    { stream: 'e', gross_cents: 0 },
  ] as any);
  const by = Object.fromEntries((db.prepare('SELECT stream, gross_cents FROM subsidiary_usage_reports').all() as any[])
    .map((x) => [x.stream, x.gross_cents]));
  assert.equal(by.a, null, 'a string that does not parse was stored as a figure');
  assert.equal(by.b, null, 'NaN was stored as a figure');
  assert.equal(by.c, null, 'Infinity was stored as a figure');
  assert.equal(by.d, 1234, 'a numeric string is still a figure, truncated to whole cents');
  assert.equal(by.e, 0, 'a real zero is a measured zero and stays one');
});

test('a re-report replaces the figure rather than adding a second quarter', async () => {
  const { env, db } = await hqEnv();
  await reportUsage(env, 'fr', SECRET, '2026-Q3', figures());
  await reportUsage(env, 'fr', SECRET, '2026-Q3', [
    { stream: 'other', gross_cents: 450_000, currency: 'EUR' },
  ] as any);

  const rows = db.prepare('SELECT * FROM subsidiary_usage_reports').all() as any[];
  assert.equal(rows.length, 1, 'a correction was filed as a second period of trading');
  assert.equal(rows[0].gross_cents, 450_000);
});

test('a report with a wrong secret writes nothing at all', async () => {
  const { env, db } = await hqEnv();
  await assert.rejects(() => reportUsage(env, 'fr', 'not-it', '2026-Q3', figures()), /wrong secret/);
  assert.equal((db.prepare('SELECT COUNT(*) AS n FROM subsidiary_usage_reports').get() as any).n, 0);
});

test('a report against a period that is not a quarter writes nothing', async () => {
  const { env, db } = await hqEnv();
  for (const bad of ['2026-13', '2026-Q5', 'Q3', '']) {
    await assert.rejects(() => reportUsage(env, 'fr', SECRET, bad, figures()), /is not a period/);
  }
  assert.equal((db.prepare('SELECT COUNT(*) AS n FROM subsidiary_usage_reports').get() as any).n, 0);
});

test('a nameless stream is dropped rather than written as an empty one', async () => {
  const { env, db } = await hqEnv();
  const r = await reportUsage(env, 'fr', SECRET, '2026-Q3', [
    { stream: '   ', gross_cents: 1 }, { stream: 'other', gross_cents: 2 },
  ] as any);
  assert.equal(r.streams, 1);
  const rows = db.prepare('SELECT stream FROM subsidiary_usage_reports').all() as any[];
  assert.deepEqual(rows.map((x) => x.stream), ['other']);
});

