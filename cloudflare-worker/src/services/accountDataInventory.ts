/** The columns of a table that name a person, from its columns and its foreign keys to `users` (`users` itself: its `id` too). */
export function personColumnsOf(t: { name?: string; columns: readonly string[]; userForeignKeys?: readonly string[] }): string[] {
  return [...new Set([...(t.name === 'users' ? ['id'] : []), ...t.columns.filter((c) => PERSON_USER_ID.test(c)), ...(t.userForeignKeys ?? []), ...t.columns.filter((c) => PERSON_EMAIL.test(c))])];
}

/** The D1 tables a schema says must be listed (they name a person) that the inventory lacks. */
export function unlistedTables(
  schema: ReadonlyArray<{ name: string; columns: readonly string[]; userForeignKeys?: readonly string[] }>,
  stores: readonly AccountStore[] = ACCOUNT_STORES,
): string[] {
  const listed = new Set(stores.filter((s) => s.kind === 'd1_table').map((s) => s.name));
  return schema.filter((t) => personColumnsOf(t).length > 0 && !listed.has(t.name)).map((t) => t.name);
}

/** Every answer still waiting for the owner, as `[store id, question]`. */
export function unspecifiedAnswers(stores: readonly AccountStore[] = ACCOUNT_STORES): Array<[string, QuestionId]> {
  return stores.flatMap((s) => (s.account_erasure.is === 'unspecified' ? [[s.id, s.account_erasure.question] as [string, QuestionId]] : []));
}
