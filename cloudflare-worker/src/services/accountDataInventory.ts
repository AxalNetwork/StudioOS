/**
 * D9045 (#9045) — the account data inventory: every store that names a person (a user id or an email address), what
 * account erasure does to it today, and whether the member's data export carries it. It is the person-level partner
 * of `ventureSpaceDataInventory.ts` (D8530) and has the same shape. This module is the single source;
 * `documentation/operations/PROCESSING_AND_RETENTION_5510.md` points here instead of repeating it.
 *
 * WHAT NAMES A PERSON. A D1 table with a column named `user_id` or `*_user_id`, a column named `email` or `*_email`,
 * or a foreign key to `users` under any name (`created_by`, `sponsor_user_id`, `reviewer_id`, ...); `users` itself; an
 * R2 key template under a user id; and the stores outside D1 and R2 that hold something keyed to a person. A few
 * tables carry no such column but are reached by the erasure through the person's agents (`via`): they are listed
 * because the erasure removes them.
 *
 * THE ERASURE. `eraseAccountAgents` (D1530, `agents/erasure.ts`) is the only account erasure code the platform has:
 * it asks the agent runtime to erase every agent the account sponsors, removes the account's compute requests and
 * their stored objects, removes the agent memory notes and run history, cancels the open tasks assigned to those
 * agents and ends their duties. The rest of a data-subject erasure is manual (D168, `services/dsrRequests.ts`: no
 * DELETE FROM users, no deleted_at, no anonymisation). Nothing in this file changes what it does.
 *
 * THE ANSWERS, one per store:
 *   removed       a code path deletes the person's rows or objects (`by` names it).
 *   changed       a code path rewrites them on purpose and keeps them (`by` names it).
 *   kept          they stay, for the stated reason.
 *   unspecified   nobody has decided. `today` says what the erasure does now (`untouched`, `changed`, or `unknown`
 *                 for a store the test cannot read), and `question` names the owner's question in
 *                 `documentation/architecture/decisions/D9045.md`.
 * A store D8530 also lists gives the same account-erasure answer there (the coverage test checks).
 *
 * THE EXPORT. `data_export` says whether `GET /api/settings/data-export` (`routes/settings.ts`) carries the store,
 * and which part of it.
 *
 * CI. `test/account_data_inventory_9045.test.ts` fails when a D1 table names a person and is not here (or is here and
 * no longer names one, or names them by other columns), when Worker source builds an R2 key under a user id under a
 * prefix not listed here, when the export reads a table not marked as exported, and when an unspecified answer's
 * question is not in D9045.md. `test/account_data_erasure_9045.test.ts` gives a synthetic person a row in every D1
 * store and an object under every R2 template, runs the erasure, reads every store and fails when an answer here is
 * not what the code did.
 */

/** A column that names a person by user id, and one that names a person by email address. */
export const PERSON_USER_ID = /(^|_)user_id$/;
export const PERSON_EMAIL = /(^|_)email$/;

/** The owner's questions in D9045.md: what account erasure should do to each group of stores. */
export const QUESTIONS = {
  Q1: 'The account itself and how it signs in',
  Q2: 'Financial, legal, identity and investment records, which may carry a hold',
  Q3: 'Messages, notifications, invitations, bookings and calendars',
  Q4: 'Audit trails, event histories and security logs that name the person',
  Q5: 'What the person wrote or did inside a company or a venture',
  Q6: 'The person\'s own profile, preferences, content and activity',
  Q7: 'Stores the erasure test cannot read: what erasure should do to them',
} as const;
export type QuestionId = keyof typeof QUESTIONS;

export type Today = 'untouched' | 'changed' | 'unknown';
export type ErasureAnswer =
  | { is: 'removed'; by: string }
  | { is: 'changed'; by: string }
  | { is: 'kept'; reason: string }
  | { is: 'unspecified'; question: QuestionId; today: Today };
export type ExportAnswer = { is: 'included'; what: string } | { is: 'not_included' };

export type AccountStoreKind = 'd1_table' | 'r2_prefix' | 'kv_namespace' | 'other';
export type AccountStore = {
  /** `d1:<table>`, `r2:<binding>/<prefix>`, `kv:<binding>` or `other:<binding>` (the same id D8530 uses for a store both list). */
  id: string;
  kind: AccountStoreKind;
  /** The table, the key template (`{user_id}`), or what the binding holds. */
  name: string;
  /** The columns that name the person (`via <table>.<column>` when reached through another table), or how the key does. */
  keyed_by: readonly string[];
  account_erasure: ErasureAnswer;
  data_export: ExportAnswer;
};

