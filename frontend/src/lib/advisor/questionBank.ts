export function questionsForPersona(p: Persona, opts: {
  week?: SpinoutWeek;
  tier?: TierKey;
  section?: string;
} = {}): Question[] {
  return QUESTION_BANK.filter(q => {
    if (!q.persona.includes(p)) return false;
    if (q.unlock_required && opts.week && q.unlock_required > opts.week) return false;
    if (q.section && opts.section && !q.section.startsWith(opts.section)) return false;
    return true;
  });
}

export function questionById(id: string): Question | undefined {
  return QUESTION_BANK.find(q => q.id === id);
}

