// Personal Advisor question bank.
// Source of truth for every question the advisor asks. Each question:
//   - is tagged to one or more personas
//   - writes to a specific page/column via the server-side write-router
//   - declares its importance for ranking inside the advisor
//   - may be gated by Spin-Out Lab week, tier, or feature unlock
//   - may be flagged for Market Intelligence extraction (sentiment, TALC)
//
// The shape mirrors what cloudflare-worker/src/services/advisor/writeRouter.ts
// expects. Keep `id` stable — it's the primary key the write-router maps on.

export type Persona =
  | 'newFounder'
  | 'existingFounder'
  | 'investor'
  | 'opPartnerCapital'
  | 'opPartnerServices'
  | 'opPartnerSourcing'
  | 'opPartnerMixed'
  | 'mentor';

export type SpinoutWeek = 1 | 2 | 3 | 4;

export type QType =
  | 'text'
  | 'textarea'
  | 'number'
  | 'currency'
  | 'percent'
  | 'date'
  | 'select'
  | 'multiselect'
  | 'range'
  | 'toggle'
  | 'file'
  | 'url'
  | 'email'
  | 'phone';

export type Importance = 'critical' | 'high' | 'med' | 'low';

export type TierKey =
  | 'free'
  | 'growth'
  | 'studio'
  | 'investor_free'
  | 'investor_pro'
  | 'investor_inst';

export type ValidateKey =
  | 'iso2country'
  | 'url'
  | 'email'
  | 'phone_e164'
  | 'positive_number'
  | 'percent_0_100'
  | 'iso_date'
  | 'slug'
  | 'iban'
  | 'tax_id';

export interface Question {
  id: string;
  persona: Persona[];
  section: string;
  page_target?: string;
  label: string;
  type: QType;
  options?: { value: string; label: string }[];
  required?: boolean;
  importance: Importance;
  unlock_required?: SpinoutWeek;
  tier_required?: TierKey;
  validate?: ValidateKey;
  min?: number;
  max?: number;
  step?: number;
  evidence?: 'required' | 'recommended';
  sentiment_eligible?: boolean;
  talc_eligible?: boolean;
  pii?: boolean;
  explainer: string;
  doc_anchor: string;
  followups?: { when: string; ask: string[] }[];
}

