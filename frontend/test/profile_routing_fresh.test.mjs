// PROFILE_ROUTING.md and PAGE_INVENTORY.md are generated from ROUTE_MAP.md and
// sidebarConfig.js. That is only worth anything if the generated copy on disk
// is actually current — a stale projection is exactly the failure this
// repository keeps paying for (a runbook that hardcoded a migration range, a
// cutover doc that hardcoded a route-table size, a production doc that cited a
// line number: each true when written, each wrong within a week).
//
// So this file is the freshness gate. Change ROUTE_MAP or the sidebar without
// re-running the generator and the build fails here, naming the command.
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import {
  outputs, parseRouteMap, parseSidebar, routesIn, workspacesFor,
} from '../../scripts/build-profile-routing.mjs';

const read = (p) => readFileSync(resolve(p), 'utf8');

test('the generated docs on disk match their sources', () => {
  for (const [path, expected] of outputs()) {
    assert.equal(
      read(path), expected,
      `${path} is stale. Re-run: node scripts/build-profile-routing.mjs`,
    );
  }
});

test('both generated docs carry the do-not-hand-edit stamp', () => {
  for (const [path] of outputs()) {
    const src = read(path);
    assert.match(src, /GENERATED by scripts\/build-profile-routing\.mjs/);
    assert.match(src, /do not hand-edit/);
  }
});

